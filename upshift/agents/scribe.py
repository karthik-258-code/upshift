"""Scribe: turn the run record into a merge request a human can audit in two minutes.

The body is deterministic (every edit, its justification, and the evidence URL it rests
on; before/after test results; models and cost). The short opening summary is written by
the model and falls back to a template if that call fails.
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass
from typing import Any

from upshift.agents.historian import ImpactDossier
from upshift.agents.reviewer import ReviewReport
from upshift.agents.scout import DependencyAssessment
from upshift.agents.surgeon import SurgeryResult
from upshift.core.budget import Budget
from upshift.core.bus import EventBus
from upshift.core.events import Event, EventType
from upshift.llm.client import TokenFactoryClient, content_of
from upshift.llm.router import ModelRouter, TaskClass

log = logging.getLogger(__name__)

FOOTER = (
    "Generated by [Upshift](https://gitlab.com/gitlab-ai-hackathon/transcend-october-2026/"
    "43699047/nvxnb) with NVIDIA Nemotron on Nebius Token Factory. Every edit above "
    "links to the changelog or migration guide that justifies it; tests ran in an isolated "
    "sandbox."
)


@dataclass
class MergeRequestDraft:
    title: str
    description: str
    branch: str
    commit_message: str

    def to_dict(self) -> dict[str, Any]:
        return {
            "title": self.title, "description": self.description, "branch": self.branch,
            "commit_message": self.commit_message,
        }


def _tests_line(result: dict[str, Any] | None) -> str:
    if not result:
        return "not run"
    return (
        f"{result.get('passed', 0)} passing, {result.get('failure_count', 0)} failing "
        f"of {result.get('tests', 0)} collected"
    )


class Scribe:
    agent = "scribe"

    def __init__(
        self,
        llm: TokenFactoryClient | None = None,
        router: ModelRouter | None = None,
        bus: EventBus | None = None,
    ) -> None:
        self.llm = llm
        self.router = router
        self.bus = bus

    @staticmethod
    def title(dep: DependencyAssessment) -> str:
        return f"chore(deps): upgrade {dep.name} {dep.current} -> {dep.latest}"

    @staticmethod
    def branch(dep: DependencyAssessment) -> str:
        safe = (dep.latest or "latest").replace("+", "-")
        return f"upshift/{dep.name}-{safe}"

    async def summary(
        self,
        dep: DependencyAssessment,
        dossier: ImpactDossier,
        surgery: SurgeryResult,
        run_id: str | None,
        budget: Budget | None,
    ) -> str:
        fallback = (
            f"Upgrades `{dep.name}` from {dep.current} to {dep.latest}. "
            f"{len(dossier.relevant)} documented changes affected this codebase; "
            f"{len(surgery.files_changed)} file(s) were updated and the test suite is green."
        )
        if self.llm is None or self.router is None:
            return fallback
        changes = "; ".join(e.title for e in dossier.relevant[:8]) or "none"
        prompt = (
            f"Write the opening paragraph of a merge request (max 90 words, plain prose, no "
            f"headings, no bullet points) for upgrading {dep.name} {dep.current} -> "
            f"{dep.latest}. Mention what kind of changes were required and that the suite is "
            f"green. Documented changes applied: {changes}. Files changed: "
            f"{', '.join(surgery.files_changed)}."
        )
        try:
            decision = self.router.route(TaskClass.WRITE, budget=budget)
            response = await self.llm.complete(
                decision.model, [{"role": "user", "content": prompt}], temperature=0.3,
                max_tokens=400, agent=self.agent, run_id=run_id, budget=budget,
            )
            text = content_of(response).strip()
            return text or fallback
        except Exception as exc:  # noqa: BLE001
            log.warning("scribe summary failed: %s", exc)
            return fallback

    def render(
        self,
        dep: DependencyAssessment,
        dossier: ImpactDossier,
        surgery: SurgeryResult,
        review: ReviewReport | None,
        summary: str,
    ) -> str:
        lines: list[str] = []
        if review is not None and review.blockers:
            count = len(review.blockers)
            lines += [
                f"> **Draft: the reviewer found {count} blocking issue(s) (see Review below). "
                "Do not merge until they are resolved.**",
                "",
            ]
        lines += [summary, "", "## What changed", ""]
        lines += [f"- {change}" for change in surgery.manifest_changes]
        by_file: dict[str, list[Any]] = {}
        changed = set(surgery.files_changed)
        for attempt in surgery.attempts:
            if attempt.rolled_back:
                continue
            for edit in attempt.edits:
                if (
                    edit.status == "applied" and edit.justification.strip()
                    and edit.path in changed  # skip files whose final content is unchanged
                ):
                    by_file.setdefault(edit.path, []).append(edit)
        if by_file:
            lines += ["", "## Code changes and why", ""]
            lines.append("| File | Change | Evidence |")
            lines.append("| --- | --- | --- |")
            for path, edits in by_file.items():
                reasons: list[str] = []
                urls: list[str] = []
                for edit in edits:
                    text = edit.justification.replace("|", "/").strip()
                    if text not in reasons:
                        reasons.append(text)
                    for url in re.split(r"[\s,]+", edit.evidence_url or ""):
                        if url.startswith("http") and url not in urls:
                            urls.append(url)
                change = "<br>".join(reasons[-4:])  # most recent justifications win
                evidence = " ".join(f"[source]({u})" for u in urls[:3])
                lines.append(f"| `{path}` | {change} | {evidence} |")

        if dossier.relevant:
            lines += ["", "## Documented changes that applied to this codebase", ""]
            for entry in dossier.relevant:
                symbols = f" ({', '.join(entry.matched_symbols)})" if entry.matched_symbols else ""
                lines.append(f"- **{entry.category}**: {entry.title}{symbols}")
                if entry.quote:
                    lines.append(f"  > {entry.quote[:300]} [\u2197]({entry.evidence_url})")

        lines += ["", "## Verification", ""]
        lines.append(f"- After the bare version bump: {_tests_line(surgery.after_bump)}")
        lines.append(f"- After Upshift's edits: **{_tests_line(surgery.final)}**")
        if surgery.attempts:
            lines.append("")
            lines.append("| Attempt | Model | Edits | Result |")
            lines.append("| --- | --- | --- | --- |")
            for attempt in surgery.attempts:
                applied = sum(e.status == "applied" for e in attempt.edits)
                outcome = _tests_line(attempt.verification) if attempt.verification else "no edits"
                if attempt.rolled_back:
                    outcome += f" (rolled back: {attempt.rollback_reason})"
                lines.append(f"| {attempt.number} | `{attempt.model}` | {applied} | {outcome} |")

        if review is not None:
            lines += ["", "## Review", ""]
            lines.append(f"Verdict: **{review.verdict}**. {review.summary}".strip())
            for finding in review.findings:
                where = f"`{finding.file}`" if finding.file else ""
                lines.append(f"- [{finding.severity}] {where} {finding.title}".rstrip())

        review_cost = review.cost_usd if review else 0.0
        total = round(dossier.cost_usd + surgery.cost_usd + review_cost, 4)
        used = {a.model for a in surgery.attempts}
        if dossier.model:
            used.add(dossier.model)
        models = sorted(used)
        lines += [
            "", "## Cost", "",
            f"- Token Factory usage: ${total:.4f} across {', '.join(f'`{m}`' for m in models)}",
            f"- Evidence sources: {len([s for s in dossier.sources if s.fetched])} pages "
            f"({len(dossier.search_queries)} Tavily searches)",
            "", "---", FOOTER,
        ]
        return "\n".join(lines)

    async def write(
        self,
        dep: DependencyAssessment,
        dossier: ImpactDossier,
        surgery: SurgeryResult,
        review: ReviewReport | None,
        run_id: str | None = None,
        budget: Budget | None = None,
    ) -> MergeRequestDraft:
        summary = await self.summary(dep, dossier, surgery, run_id, budget)
        title = self.title(dep)
        if review is not None and review.blockers:
            title = f"Draft: {title}"
        draft = MergeRequestDraft(
            title=title,
            description=self.render(dep, dossier, surgery, review, summary),
            branch=self.branch(dep),
            commit_message=f"{self.title(dep)}\n\n{summary}",
        )
        if self.bus is not None and run_id is not None:
            await self.bus.publish(
                Event(
                    run_id=run_id, type=EventType.AGENT_MESSAGE, agent=self.agent,
                    node_id=f"dep:{dep.name}",
                    payload={"message": "merge request drafted", **draft.to_dict()},
                )
            )
        return draft
